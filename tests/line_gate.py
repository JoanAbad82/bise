#!/usr/bin/env python3
"""The 1,000-line gate (docs/architecture-principles.md rule 5, debt D5): a change may not push
a hand-written .rs, .bend, .ts, .tsx or .py file over 1,000 lines.

The files already over 1,000 are in tests/line_limits.txt ("<lines> <path>", sorted by path), a
ratchet:
  - a listed file may not grow past its count;
  - a listed file that shrinks lowers its count in the same commit (its line goes when it is at
    1,000 or under, or when the file is gone);
  - the list only shrinks: vs the base (GATE_BASE, default HEAD) no count goes up and no path
    comes in, except a rename (a path that leaves the list in the same change, with at least as
    many lines, pays for the new one).
Exempt: generated files ("generated by" in their first 3 lines), tests' fixtures (a path with
a fixtures/ folder in it) and vendored code (bend/vendor/, rust/vendor/: we don't write it, and
a vendor update is not ours to split).

A line ending in " merge" ("<lines> <path> merge") is a count the desktop app's merge from
ambient-app will bring (architect m_19510): the whole-tree audit allows it above the file's
real count, or for a path not in the tree yet, until that merge lands (apps/desktop/ is in the
tree); then any mark left is red, and the merge sets those lines to the real counts.

  python3 tests/line_gate.py <changed path>...   the changed paths and the list (gate.sh quick)
  python3 tests/line_gate.py --all               the whole tree (gate.sh full, a release's gate):
                                                 also red on a file over 1,000 not listed (a growth
                                                 committed without the quick gate) and on a count
                                                 above its file's (headroom)
  python3 tests/line_gate.py --self-test         the rules on synthetic data

Fast: quick reads the changed files only (a listed file the change does not touch can neither
grow nor shrink) and one `git show` of the base list: ~0.1 s; --all reads every tracked source
file: ~0.5 s. Exit 1 with one line per problem.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = "tests/line_limits.txt"
LIMIT = 1000
EXTS = (".rs", ".bend", ".ts", ".tsx", ".py")
RULE = "split it: move a block to its own file (docs/architecture-principles.md rule 5)"
EXEMPT_PREFIXES = ("bend/vendor/", "rust/vendor/")
# in the tree once the desktop app's merge has landed: the " merge" marks end there
MERGED_WHEN = "apps/desktop/"


def in_scope(path, head):
    """A hand-written source file the gate counts. head: its first bytes. Pure."""
    if not path.endswith(EXTS) or path.startswith(EXEMPT_PREFIXES) or "fixtures" in path.split("/")[:-1]:
        return False
    first = b"\n".join(head.split(b"\n")[:3]).lower()
    return b"generated by" not in first


def parse(text):
    """({path: lines}, {paths marked merge}, [bad rows]) of a list file. Pure."""
    caps, marked, bad = {}, set(), []
    for n, row in enumerate(text.splitlines(), 1):
        row = row.strip()
        if not row or row.startswith("#"):
            continue
        parts = row.split()
        if len(parts) not in (2, 3) or not parts[0].isdigit() or parts[2:] not in ([], ["merge"]):
            bad.append("%s:%d: '%s': want '<lines> <path>' or '<lines> <path> merge'" % (LIST, n, row))
        elif parts[1] in caps:
            bad.append("%s:%d: %s is listed twice" % (LIST, n, parts[1]))
        else:
            caps[parts[1]] = int(parts[0])
            if parts[2:]:
                marked.add(parts[1])
    return caps, marked, bad


def check_files(counts, caps, headroom=frozenset()):
    """Problems of the files counted. counts: {path: lines, or None when gone} of the in-scope
    paths to check; caps: the list; headroom: listed paths whose count may stay above their
    file's, or name no file yet (the merge marks, in the audit). Pure."""
    out = []
    for path in sorted(counts):
        n, cap = counts[path], caps.get(path)
        if path in headroom and (n is None or LIMIT < n < cap):
            continue
        if n is None:
            if cap is not None:
                out.append("%s: gone: remove its line from %s" % (path, LIST))
        elif cap is None:
            if n > LIMIT:
                out.append("%s: %d lines, over %d: %s" % (path, n, LIMIT, RULE))
        elif n > cap:
            out.append("%s: %d lines, over its listed %d in %s: %s" % (path, n, cap, LIST, RULE))
        elif n <= LIMIT:
            out.append("%s: %d lines, at %d or under now: remove its line from %s" % (path, n, LIMIT, LIST))
        elif n < cap:
            out.append("%s: %d lines, under its listed %d: lower its line in %s to %d" % (path, n, cap, LIST, n))
    return out


def check_list(caps, base):
    """The list only shrinks vs base ({path: lines}, None when the base has no list). Pure."""
    if base is None:
        return []
    out = []
    for path in sorted(caps):
        if path in base and caps[path] > base[path]:
            out.append("%s: %s raised from %d to %d: the list only shrinks: %s" % (LIST, path, base[path], caps[path], RULE))
    # a new path is a rename when a path that left the list had at least as many lines
    left = sorted((base[p] for p in base if p not in caps), reverse=True)
    for path in sorted((p for p in caps if p not in base), key=lambda p: -caps[p]):
        if left and left[0] >= caps[path]:
            left.pop(0)
        else:
            out.append("%s: %s is new in the list: the list only shrinks: %s" % (LIST, path, RULE))
    return out


def count(path):
    """(lines, in scope) of a file of the tree, (None, True) when it is gone."""
    try:
        with open(os.path.join(ROOT, path), "rb") as f:
            body = f.read()
    except (FileNotFoundError, IsADirectoryError, NotADirectoryError):
        return None, path.endswith(EXTS)
    return body.count(b"\n"), in_scope(path, body[:512])


def base_list():
    """The list at GATE_BASE (default HEAD), None when it has none."""
    r = subprocess.run(["git", "-C", ROOT, "show", "%s:%s" % (os.environ.get("GATE_BASE", "HEAD"), LIST)],
                       capture_output=True)
    return parse(r.stdout.decode())[0] if r.returncode == 0 else None


def check_marks(marked, merged):
    """The merge marks left once the desktop app's merge has landed. Pure."""
    if not merged:
        return []
    return ["%s: %s still marked merge: the desktop merge landed (%s is in the tree): set its real count, drop the mark"
            % (LIST, path, MERGED_WHEN) for path in sorted(marked)]


def check(paths, audit=False):
    """Every problem of these paths (repo-relative) and of the list; audit: paths are the whole
    tree, and every listed path is checked too."""
    try:
        with open(os.path.join(ROOT, LIST)) as f:
            caps, marked, bad = parse(f.read())
    except FileNotFoundError:
        caps, marked, bad = {}, set(), ["%s: missing" % LIST]
    merged = any(p.startswith(MERGED_WHEN) for p in paths) if audit else False
    counts = {}
    # quick: only the changed paths (a listed file the change does not touch can neither grow
    # nor shrink); the audit: every tracked file and every listed path
    for path in set(paths) | (set(caps) if audit else set()):
        n, scoped = count(path)
        if scoped:
            counts[path] = n
        elif path in caps:
            bad.append("%s: %s is exempt (generated, vendored, a fixture, or not a source file): remove its line" % (LIST, path))
    headroom = frozenset(marked) if audit and not merged else frozenset()
    return (bad + check_files(counts, caps, headroom) + check_list(caps, base_list())
            + (check_marks(marked, merged) if audit else []))


def self_test():
    wrong = []
    def want(what, got, expected):
        if got != expected:
            wrong.append("%s: got %r, want %r" % (what, got, expected))
    want("scope rs", in_scope("rust/a.rs", b"//! x\n"), True)
    want("scope md", in_scope("docs/a.md", b"x\n"), False)
    want("scope js", in_scope("apps/a.js", b"x\n"), False)
    want("scope fixture", in_scope("tests/fixtures/a.py", b"x\n"), False)
    want("scope fixture deep", in_scope("rust/proto/tests/fixtures/x/a.rs", b"x\n"), False)
    want("scope fixtures file", in_scope("tests/fixtures.py", b"x\n"), True)
    want("scope generated", in_scope("bend/hub/gen/a.bend", b"# Generated by bise-proto\n"), False)
    want("scope generated line 3", in_scope("a.ts", b"// a\n// b\n// generated by x\n"), False)
    want("scope generated line 4", in_scope("a.ts", b"// a\n// b\n// c\n// generated by x\n"), True)
    caps = {"big.rs": 1200}
    want("new file under", check_files({"a.rs": 1000}, caps), [])
    want("new file over", len(check_files({"a.rs": 1001}, caps)), 1)
    want("listed same", check_files({"big.rs": 1200}, caps), [])
    want("listed grew", "over its listed" in check_files({"big.rs": 1201}, caps)[0], True)
    want("listed shrank", "lower its line" in check_files({"big.rs": 1100}, caps)[0], True)
    want("listed under limit", "remove its line" in check_files({"big.rs": 999}, caps)[0], True)
    want("listed gone", "gone" in check_files({"big.rs": None}, caps)[0], True)
    want("unlisted gone", check_files({"a.rs": None}, caps), [])
    want("parse", parse("# c\n\n1200 big.rs\nx\n1 big.rs\n"),
         ({"big.rs": 1200}, set(), ["%s:4: 'x': want '<lines> <path>' or '<lines> <path> merge'" % LIST,
                                    "%s:5: big.rs is listed twice" % LIST]))
    want("parse merge", parse("1200 a.rs merge\n1300 b.rs\n1 c.rs other\n")[:2], ({"a.rs": 1200, "b.rs": 1300}, {"a.rs"}))
    want("scope vendor", in_scope("bend/vendor/json.bend", b"x\n"), False)
    want("scope rust vendor", in_scope("rust/vendor/crossterm/src/event.rs", b"x\n"), False)
    want("scope not vendor", in_scope("rust/tui/src/vendor.rs", b"x\n"), True)
    mark = frozenset({"big.rs"})
    want("headroom under", check_files({"big.rs": 1100}, caps, mark), [])
    want("headroom no file yet", check_files({"big.rs": None}, caps, mark), [])
    want("headroom same", check_files({"big.rs": 1200}, caps, mark), [])
    want("headroom grew", len(check_files({"big.rs": 1201}, caps, mark)), 1)
    want("headroom at limit", len(check_files({"big.rs": 1000}, caps, mark)), 1)
    want("headroom other file", len(check_files({"a.rs": 1100}, {"a.rs": 1200}, mark)), 1)
    want("refusal says what to do", check_files({"big.rs": 1201}, caps)[0].endswith(RULE), True)
    want("marks before merge", check_marks({"big.rs"}, False), [])
    want("marks after merge", len(check_marks({"big.rs"}, True)), 1)
    base = {"a.rs": 1500, "b.rs": 1100}
    want("list same", check_list(dict(base), base), [])
    want("list no base", check_list({"x.rs": 5000}, None), [])
    want("list shrank", check_list({"a.rs": 1400}, base), [])
    want("list dropped", check_list({"a.rs": 1500}, base), [])
    want("list raised", len(check_list({"a.rs": 1501, "b.rs": 1100}, base)), 1)
    want("list new", len(check_list({"a.rs": 1500, "b.rs": 1100, "c.rs": 1001}, base)), 1)
    want("list rename", check_list({"a2.rs": 1500, "b.rs": 1100}, base), [])
    want("list rename smaller", check_list({"a2.rs": 1300, "b.rs": 1100}, base), [])
    want("list rename bigger", len(check_list({"a2.rs": 1501, "b.rs": 1100}, base)), 1)
    want("list one rename pays once", len(check_list({"x.rs": 1100, "y.rs": 1100}, base)), 0)
    want("list two new one left", len(check_list({"x.rs": 1100, "y.rs": 1100, "z.rs": 1100, "b.rs": 1100}, base)), 2)
    if wrong:
        raise SystemExit("line-gate self-test failed:\n  " + "\n  ".join(wrong))


def main():
    self_test()
    args = sys.argv[1:]
    if args == ["--self-test"]:
        print("line-gate: self-test ok")
        return
    audit = args == ["--all"]
    if audit:
        # every tracked path: the sources, and apps/desktop/ for MERGED_WHEN
        args = subprocess.run(["git", "-C", ROOT, "ls-files"], capture_output=True, text=True).stdout.split()
    problems = check([a for a in args if a.endswith(EXTS) or a == LIST or a.startswith(MERGED_WHEN)], audit)
    if problems:
        print("\n".join(problems))
        sys.exit(1)


if __name__ == "__main__":
    main()
