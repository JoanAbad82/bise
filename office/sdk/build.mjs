// Builds src/ into office/dist/office.js: one ESM bundle, no node imports
// (platform neutral, so an `fs` or `node:` import fails the build), the
// same bytes for the same sources and lockfile; and src/view/ into
// office/dist/office-view.js, the viewer's docx renderer (browser only).
// Committed (cargo and nix never run pnpm); shipped in the app root
// (scripts/versions.sh), where the page server and bise office run read it.
//
//   node build.mjs           write ../dist/office.js and ../dist/office-view.js
//   node build.mjs --check   rebuild in memory, exit 1 when a committed file differs
//                            (tests/office_check.sh, gate.sh)

import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");
const banner = { js: "// generated by office/sdk/build.mjs from office/sdk/src, never hand-edited:\n// pnpm -C office/sdk build (docs/office.md). Third-party code in it: THIRD_PARTY_NOTICES." };

// office.js: the SDK, for bise office run, the viewer and the tests; no DOM, no node
// office-view.js: what draws a docx in the viewer (docx-preview + jszip), browser only,
//   loaded by kit/office/docx.js alone (architect m_23781); fails past 2 MB
const bundles = [
  { file: "office.js", entry: join("src", "index.ts"), platform: "neutral", mainFields: ["module", "main"] },
  { file: "office-view.js", entry: join("src", "view", "index.ts"), platform: "browser", max: 2 * 1024 * 1024 },
];

// what V8 alone (bend-jsrt's script mode) and a browser lack: none may stay
const banned = [/\brequire\(\s*["']/, /from\s*["']node:/, /import\(\s*["']node:/, /\bprocess\.env\b/, /\bBuffer\.from\b/];

let failed = false;
for (const b of bundles) {
  const out = join(here, "..", "dist", b.file);
  const res = await build({
    entryPoints: [join(here, b.entry)],
    bundle: true,
    format: "esm",
    platform: b.platform,
    ...(b.mainFields ? { mainFields: b.mainFields } : {}),
    target: "es2022",
    write: false,
    minify: false,
    charset: "utf8",
    legalComments: "eof",
    logLevel: "warning",
    banner,
  });
  const js = res.outputFiles[0].text;
  const hit = b.platform === "neutral" && banned.find((re) => re.test(js));
  if (hit) {
    console.error(`${b.file} uses ${hit}: the bundle must run without node (docs/office.md)`);
    process.exit(1);
  }
  const size = new TextEncoder().encode(js).length;
  if (b.max && size > b.max) {
    console.error(`${b.file} is ${size} bytes, over its ${b.max} budget (architect m_23781)`);
    process.exit(1);
  }
  if (check) {
    let have = "";
    try {
      have = readFileSync(out, "utf8");
    } catch {}
    if (have !== js) {
      console.error(`office/dist/${b.file} is stale or hand-edited: run pnpm -C office/sdk build and commit it`);
      failed = true;
    } else console.log(`office/dist/${b.file} is fresh (${js.length} bytes)`);
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, js);
    console.log(`wrote office/dist/${b.file} (${js.length} bytes)`);
  }
}
if (failed) process.exit(1);
