// Builds src/ into office/dist/office.js: one ESM bundle, no node imports
// (platform neutral, so an `fs` or `node:` import fails the build), the
// same bytes for the same sources and lockfile. Committed (cargo and nix
// never run pnpm: `include_str!` and the viewer read this one file).
//
//   node build.mjs           write ../dist/office.js
//   node build.mjs --check   rebuild in memory, exit 1 when the committed file differs
//                            (tests/office_check.sh, gate.sh)

import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "dist", "office.js");
const check = process.argv.includes("--check");

const res = await build({
  entryPoints: [join(here, "src", "index.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "es2022",
  write: false,
  minify: false,
  charset: "utf8",
  legalComments: "eof",
  logLevel: "warning",
  banner: { js: "// generated by office/sdk/build.mjs from office/sdk/src, never hand-edited:\n// pnpm -C office/sdk build (docs/office.md). Third-party code in it: THIRD_PARTY_NOTICES." },
});
const js = res.outputFiles[0].text;

// what V8 alone (bend-jsrt's script mode) and a browser lack: none may stay
const banned = [/\brequire\(\s*["']/, /from\s*["']node:/, /import\(\s*["']node:/, /\bprocess\.env\b/, /\bBuffer\.from\b/];
const hit = banned.find((re) => re.test(js));
if (hit) {
  console.error(`office.js uses ${hit}: the bundle must run without node (docs/office.md)`);
  process.exit(1);
}

if (check) {
  let have = "";
  try {
    have = readFileSync(out, "utf8");
  } catch {}
  if (have !== js) {
    console.error("office/dist/office.js is stale or hand-edited: run pnpm -C office/sdk build and commit it");
    process.exit(1);
  }
  console.log(`office/dist/office.js is fresh (${js.length} bytes)`);
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, js);
  console.log(`wrote office/dist/office.js (${js.length} bytes)`);
}
